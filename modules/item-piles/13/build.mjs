#!/usr/bin/env node
/** Deterministic package generation; the installed loader consumes plain scripts. */
import { mkdir, readFile, readdir, unlink, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { Script } from 'node:vm';
import { createRuntime, metadata, operations } from './src/registry.mjs';
import { legacyBinding, legacyProbe } from './src/legacy.mjs';

export const packageRoot = dirname(fileURLToPath(import.meta.url));
export const generatedMarker = '// Generated by modules/item-piles/13/build.mjs; do not edit.';

function record(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function validateRegistry() {
  const ids = new Set();
  for (const operation of operations) {
    if (typeof operation.id !== 'string' || !/^[a-z][a-z0-9_]*$/.test(operation.id) || ids.has(operation.id)) {
      throw new Error(`Invalid or duplicate Item Piles operation: ${operation.id}`);
    }
    ids.add(operation.id);
    if (typeof operation.description !== 'string' || !operation.description.trim()) {
      throw new Error(`Missing description for ${operation.id}`);
    }
    if (typeof operation.readOnly !== 'boolean' || typeof operation.handler !== 'function') {
      throw new Error(`Missing write classification or handler for ${operation.id}`);
    }
    if (!record(operation.inputSchema) || operation.inputSchema.type !== 'object' ||
        operation.inputSchema.additionalProperties !== false || !record(operation.outputSchema)) {
      throw new Error(`Invalid input/output schema contract for ${operation.id}`);
    }
    if (record(operation.inputSchema.properties) && 'target_id' in operation.inputSchema.properties) {
      throw new Error(`target_id is reserved for MCP routing (${operation.id})`);
    }
    if (!Array.isArray(operation.requiredMethods) ||
        operation.requiredMethods.some((method) =>
          typeof method !== 'string' || !/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(method))) {
      throw new Error(`Invalid API requirements for ${operation.id}`);
    }
  }
  if (!ids.has('get_items')) throw new Error('The existing get_items contract must remain available');
}

/** Build in memory: --check and tests never rewrite the package. */
export function generatedFiles() {
  validateRegistry();
  const files = new Map();
  const definitions = [];
  const factory = createRuntime.toString().replace(/\r\n/g, '\n');
  for (const operation of operations) {
    const legacy = operation.id === 'get_items';
    const binding = legacy ? 'get_items.js' : `bindings/${operation.id}.js`;
    const probe = legacy ? 'probe.js' : `probes/${operation.id}.js`;
    const options = JSON.stringify({
      readOnly: operation.readOnly,
      requiredMethods: [...new Set(operation.requiredMethods)].sort(),
      legacy,
    });
    const header = `${generatedMarker}\n// Operation: ${operation.id}; edit src/ and run build.mjs --write.\n`;
    const handler = operation.handler.toString().replace(/\r\n/g, '\n');
    const script = legacy ? legacyBinding : `${header}const runtime = await (${factory})(${options});\n` +
      `return await (${handler})(args, runtime);\n`;
    // Factory construction only validates readiness and creates helpers. It
    // does not invoke an operation, mutate Foundry or resolve caller documents.
    const check = legacy ? legacyProbe : `${header}// INTEGRATION_PROBE: package-owned readiness policy.\n` +
      `try {\n  await (${factory})(${options});\n  return { ready: true };\n` +
      `} catch (error) {\n  return { ready: false, reason: error instanceof Error ? error.message : String(error) };\n}\n`;
    new Script(`(async () => {\n${script}\n})()`, { filename: binding });
    new Script(`(async () => {\n${check}\n})()`, { filename: probe });
    files.set(binding, script);
    files.set(probe, check);
    definitions.push({
      id: operation.id,
      description: operation.description + (operation.readOnly ? '' :
        ' WRITE: requires the selected target\'s writeEnabled=true and a GM execution runtime. An outcome_unknown result must not be retried automatically.'),
      inputSchema: operation.inputSchema,
      outputSchema: operation.outputSchema,
      binding,
      probe,
      readOnly: operation.readOnly,
    });
  }
  files.set('manifest.json', JSON.stringify({ ...metadata, operations: definitions }, null, 2) + '\n');
  return files;
}

async function obsoleteFiles(root, expected) {
  const obsolete = [];
  for (const directory of ['bindings', 'probes']) {
    let entries;
    try {
      entries = await readdir(join(root, directory), { withFileTypes: true });
    } catch (error) {
      if (error.code === 'ENOENT') continue;
      throw error;
    }
    for (const entry of entries) {
      const path = `${directory}/${entry.name}`;
      if (!entry.isFile() || !entry.name.endsWith('.js')) {
        throw new Error(`Unexpected path in generated output directory: ${path}`);
      }
      if (!expected.has(path)) obsolete.push(path);
    }
  }
  return obsolete.sort();
}

export async function generatePackage({ mode = 'check', root = packageRoot } = {}) {
  if (!['check', 'write'].includes(mode)) throw new Error(`Unknown generation mode: ${mode}`);
  const files = generatedFiles();
  const obsolete = await obsoleteFiles(root, files);
  if (mode === 'check') {
    const differences = [...obsolete.map((path) => `orphan: ${path}`)];
    for (const [path, expected] of files) {
      try {
        if (await readFile(join(root, path), 'utf8') !== expected) differences.push(`changed: ${path}`);
      } catch (error) {
        if (error.code === 'ENOENT') differences.push(`missing: ${path}`);
        else throw error;
      }
    }
    if (differences.length) {
      throw new Error(`Item Piles generated files are out of date:\n${differences.join('\n')}\nRun node modules/item-piles/13/build.mjs --write`);
    }
  } else {
    // Refuse to delete a hand-written file in a generated directory. Check all
    // removals before writing anything, then remove only identified old outputs.
    for (const path of obsolete) {
      if (!(await readFile(join(root, path), 'utf8')).startsWith(generatedMarker)) {
        throw new Error(`Refusing to remove an unrecognized file: ${path}`);
      }
    }
    for (const [path, contents] of files) {
      await mkdir(dirname(join(root, path)), { recursive: true });
      await writeFile(join(root, path), contents);
    }
    for (const path of obsolete) await unlink(join(root, path));
  }
  return { operations: operations.length, files: files.size };
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  const args = process.argv.slice(2);
  if (args.length !== 1 || !['--write', '--check'].includes(args[0])) {
    throw new Error('Usage: node modules/item-piles/13/build.mjs --write|--check');
  }
  const result = await generatePackage({ mode: args[0].slice(2) });
  console.log(`Item Piles ${args[0]}: ${result.operations} operations, ${result.files} generated files`);
}
